#!/usr/bin/env python
"""Generate `solution/gold.patch` from `solution/fixed/`.

Hand-writing unified diffs is miserable and error-prone, so nobody does it here.
Instead, an author drops the **fixed version of each changed file** into
`solution/fixed/`, mirroring its path under `repo/`:

    tasks/train/bugfix_offbyone_pagination/
        repo/src/pagination.py            <- the broken file the agent sees
        solution/fixed/src/pagination.py  <- the same file, fixed
        solution/gold.patch               <- GENERATED from the two

`solution/` is never materialised into the sandbox (see task_loader.materialise), so
the fixed source cannot leak to the agent.

    uv run python benchmark/tools/make_gold_patch.py --task bugfix_offbyone_pagination
    uv run python benchmark/tools/make_gold_patch.py --all --check   # CI: fail if stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from benchmark.tools.patch_utils import apply_patch  # noqa: E402
from benchmark.tools.task_loader import SPLITS, TASKS_ROOT, Task, iter_tasks, load_task  # noqa: E402

HEADER = (
    "# GENERATED by benchmark/tools/make_gold_patch.py from solution/fixed/ - do not hand-edit.\n"
    "# Paths are relative to the task directory. Regenerate with:\n"
    "#   uv run python benchmark/tools/make_gold_patch.py --task {task_id}\n"
)


def build_patch(task: Task) -> str:
    """Diff every file in solution/fixed/ against its counterpart under repo/."""
    fixed_root = task.path / "solution" / "fixed"
    if not fixed_root.is_dir():
        raise SystemExit(
            f"{task.id}: no solution/fixed/ directory.\n"
            f"  Create it and copy in the FIXED version of each file the gold patch should change,\n"
            f"  keeping the same path it has under repo/. Example:\n"
            f"    solution/fixed/src/pagination.py"
        )

    import difflib

    chunks: list[str] = []
    changed = 0
    for fixed_file in sorted(p for p in fixed_root.rglob("*") if p.is_file()):
        rel = fixed_file.relative_to(fixed_root).as_posix()
        if "__pycache__" in rel or rel.endswith(".pyc"):
            continue
        original = task.repo_dir / rel
        new_lines = _lines(fixed_file)
        old_lines = _lines(original) if original.is_file() else None

        if old_lines == new_lines:
            continue
        changed += 1
        diff = difflib.unified_diff(
            old_lines if old_lines is not None else [],
            new_lines,
            fromfile="/dev/null" if old_lines is None else f"a/repo/{rel}",
            tofile=f"b/repo/{rel}",
            n=3,
            lineterm="",
        )
        chunks.append("\n".join(diff))

    if not changed:
        raise SystemExit(
            f"{task.id}: solution/fixed/ is identical to repo/ - the gold patch would be empty.\n"
            f"  Did you forget to break the repo, or forget to fix solution/fixed/?"
        )
    return HEADER.format(task_id=task.id) + "\n".join(chunks) + "\n"


def _lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n").replace("\r", "\n").split("\n")


def verify_applies(task: Task, patch_text: str) -> None:
    """Dry-run the freshly built patch against a scratch copy of repo/, so a broken
    generator is caught here rather than three hours later in `make validate`."""
    import tempfile
    from shutil import copytree, ignore_patterns, rmtree

    tmp = Path(tempfile.mkdtemp(prefix=f"goldcheck_{task.id}_"))
    try:
        copytree(task.repo_dir, tmp / "repo", ignore=ignore_patterns("__pycache__", "*.pyc"))
        apply_patch(tmp, patch_text)
        fixed_root = task.path / "solution" / "fixed"
        for fixed_file in sorted(p for p in fixed_root.rglob("*") if p.is_file()):
            rel = fixed_file.relative_to(fixed_root).as_posix()
            if "__pycache__" in rel:
                continue
            got = (tmp / "repo" / rel).read_text(encoding="utf-8").replace("\r\n", "\n")
            want = fixed_file.read_text(encoding="utf-8").replace("\r\n", "\n")
            if got != want:
                raise SystemExit(f"{task.id}: applying the generated patch did not reproduce solution/fixed/{rel}")
    finally:
        rmtree(tmp, ignore_errors=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--task", help="Task id.")
    group.add_argument("--all", action="store_true", help="Every task in every split.")
    parser.add_argument("--check", action="store_true", help="Do not write; exit 1 if any patch is stale.")
    args = parser.parse_args()

    if args.task:
        dirs = [TASKS_ROOT / split / args.task for split in SPLITS]
        found = [d for d in dirs if d.is_dir()]
        if not found:
            print(f"No task directory named '{args.task}'", file=sys.stderr)
            return 2
        tasks = [load_task(found[0])]
    else:
        tasks = list(iter_tasks())

    stale: list[str] = []
    for task in tasks:
        patch_text = build_patch(task)
        verify_applies(task, patch_text)
        target = task.gold_patch_path
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == patch_text:
            print(f"  ok    {task.split}/{task.id}")
            continue
        if args.check:
            stale.append(task.id)
            print(f"  STALE {task.split}/{task.id}")
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(patch_text, encoding="utf-8", newline="\n")
        print(f"  wrote {task.split}/{task.id}  ({len(patch_text.splitlines())} lines)")

    if stale:
        print(f"\n{len(stale)} gold patch(es) out of date. Regenerate: make gold-patches")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
